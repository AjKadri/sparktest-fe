#!/usr/bin/env python3
"""Generates tests-erc20/src/{original,buggy}.fe from one template: the same properties run against the unchanged
vendored ERC20 (examples/erc20) and against the planted-bug copy (examples/erc20-buggy)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEMPLATE = '''// GENERATED by scripts/gen_erc20_tests.py -- do not edit by hand. @WHAT@
use std::evm::{Evm, Address}
use sparktest::{check, Config, Summary, summarize}
use sparktest_evm::fixed_seed
use @MOD@::CoolCoin
use ingot::actor::Actor
use ingot::client::{total_supply, balance_of, allowance, actor_transfer, actor_approve, actor_transfer_from}

#[event]
struct Pr { id: u256, failed: u256, case: u256, steps: u256, o0: u256, o1: u256, o2: u256, o3: u256, s0: u256, s1: u256, s2: u256, s3: u256, gas: u256 }

fn emit_pr(_ id: u256, _ s: Summary, _ gas: u256) uses (evm: mut Evm) {
    evm.emit(Pr { id, failed: s.failed, case: s.case, steps: s.steps,
        o0: s.original[0], o1: s.original[1], o2: s.original[2], o3: s.original[3],
        s0: s.shrunk[0], s1: s.shrunk[1], s2: s.shrunk[2], s3: s.shrunk[3], gas })
}

// four actor proxies (distinct msg.senders); index % 4 picks one, so self-transfers and repeated actors are common
fn deploy_actors() -> [Address; 4] uses (evm: mut Evm) {
    let a0 = evm.create<Actor>(value: Wei::zero(), args: ())
    let a1 = evm.create<Actor>(value: Wei::zero(), args: ())
    let a2 = evm.create<Actor>(value: Wei::zero(), args: ())
    let a3 = evm.create<Actor>(value: Wei::zero(), args: ())
    [a0, a1, a2, a3]
}

// a fresh token per case: supply 1000 to actor 0, which sends 250 to each other actor (every actor holds 250)
fn fresh_token(_ actors: [Address; 4]) -> Address uses (evm: mut Evm) {
    let token = evm.create<CoolCoin>(value: Wei::zero(), args: (1000 as u256, actors[0]))
    let _ = actor_transfer(actors[0], token, actors[1], 250)
    let _ = actor_transfer(actors[0], token, actors[2], 250)
    let _ = actor_transfer(actors[0], token, actors[3], 250)
    token
}

fn who(_ actors: [Address; 4], _ i: u8) -> Address { actors[(i % 4) as usize] }

fn sum_balances(_ token: Address, _ actors: [Address; 4]) -> u256 uses (evm: mut Evm) {
    balance_of(token, actors[0]) + balance_of(token, actors[1]) + balance_of(token, actors[2]) + balance_of(token, actors[3])
}

// P1: transfer(amount <= balance) succeeds and moves exactly amount (a self-transfer moves nothing)
fn p1(_ actors: [Address; 4], _ p: (u8, u8, u16)) -> bool uses (evm: mut Evm) {
    let token = fresh_token(actors)
    let from = who(actors, p.0)
    let to = who(actors, p.1)
    let bf = balance_of(token, from)
    let bt = balance_of(token, to)
    let amount = (p.2 as u256) % (bf + 1)
    if actor_transfer(from, token, to, amount) != 1 { return false }
    let af = balance_of(token, from)
    let at = balance_of(token, to)
    if p.0 % 4 == p.1 % 4 { return af == bf && at == bt }
    af == bf - amount && at == bt + amount
}

// P2: transfer(amount > balance) does not succeed and changes nothing
fn p2(_ actors: [Address; 4], _ p: (u8, u8, u16)) -> bool uses (evm: mut Evm) {
    let token = fresh_token(actors)
    let from = who(actors, p.0)
    let to = who(actors, p.1)
    let bf = balance_of(token, from)
    let bt = balance_of(token, to)
    let amount = bf + 1 + (p.2 as u256)
    if actor_transfer(from, token, to, amount) != 0 { return false }
    balance_of(token, from) == bf && balance_of(token, to) == bt && total_supply(token) == 1000
}

// P3: transfers never change totalSupply (whether or not they succeed)
fn p3(_ actors: [Address; 4], _ p: (u8, u8, u32)) -> bool uses (evm: mut Evm) {
    let token = fresh_token(actors)
    let before = total_supply(token)
    let _ = actor_transfer(who(actors, p.0), token, who(actors, p.1), p.2 as u256)
    total_supply(token) == before
}

// P4: approve then transferFrom(amount <= allowance): allowance drops by exactly amount, balances move exactly amount
// input: (owner, spender, to, packed) where allowance = packed % 65536 and the requested amount = packed / 65536
fn p4(_ actors: [Address; 4], _ p: (u8, u8, u8, u32)) -> bool uses (evm: mut Evm) {
    let token = fresh_token(actors)
    let owner = who(actors, p.0)
    let spender = who(actors, p.1)
    let to = who(actors, p.2)
    let allowed = (p.3 % 65536) as u256
    if actor_approve(owner, token, spender, allowed) != 1 { return false }
    let bo = balance_of(token, owner)
    let bt = balance_of(token, to)
    let cap = if allowed < bo { allowed } else { bo }
    let amount = ((p.3 / 65536) as u256) % (cap + 1)
    if actor_transfer_from(spender, token, owner, to, amount) != 1 { return false }
    if allowance(token, owner, spender) != allowed - amount { return false }
    if p.0 % 4 == p.2 % 4 { return balance_of(token, owner) == bo }
    balance_of(token, owner) == bo - amount && balance_of(token, to) == bt + amount
}

// P5: transferFrom(amount > allowance) does not succeed and leaves the allowance alone
fn p5(_ actors: [Address; 4], _ p: (u8, u8, u8, u32)) -> bool uses (evm: mut Evm) {
    let token = fresh_token(actors)
    let owner = who(actors, p.0)
    let spender = who(actors, p.1)
    let to = who(actors, p.2)
    let allowed = (p.3 % 65536) as u256
    if actor_approve(owner, token, spender, allowed) != 1 { return false }
    let amount = allowed + 1 + ((p.3 / 65536) as u256)
    if actor_transfer_from(spender, token, owner, to, amount) != 0 { return false }
    allowance(token, owner, spender) == allowed
}

// P6: conservation: after any transfer the four balances still add up to totalSupply
fn p6(_ actors: [Address; 4], _ p: (u8, u8, u16)) -> bool uses (evm: mut Evm) {
    let token = fresh_token(actors)
    let from = who(actors, p.0)
    let amount = (p.2 as u256) % (balance_of(token, from) + 1)
    let _ = actor_transfer(from, token, who(actors, p.1), amount)
    sum_balances(token, actors) == total_supply(token)
}
'''

PROPS = [
    # id, name, text, fn, input type
    (1, 'p1_transfer_moves_exactly_amount', 'p1', '(u8, u8, u16)'),
    (2, 'p2_transfer_over_balance_changes_nothing', 'p2', '(u8, u8, u16)'),
    (3, 'p3_transfer_keeps_total_supply', 'p3', '(u8, u8, u32)'),
    (4, 'p4_transfer_from_lowers_allowance_exactly', 'p4', '(u8, u8, u8, u32)'),
    (5, 'p5_transfer_from_over_allowance_fails', 'p5', '(u8, u8, u8, u32)'),
    (6, 'p6_balances_sum_to_total_supply', 'p6', '(u8, u8, u16)'),
]

def gen(mod, base, prefix, what, expect_fail, idx=False):
    t = TEMPLATE
    if idx:
        # actors chosen with Index<4> (bounded, shrinks inside 0..3) instead of a raw u8 taken % 4
        t = t.replace('use sparktest::{check, Config, Summary, summarize}', 'use sparktest::{check, Config, Summary, summarize, Index}')
        t = t.replace('fn who(_ actors: [Address; 4], _ i: u8) -> Address { actors[(i % 4) as usize] }', 'fn who(_ actors: [Address; 4], _ i: Index<4>) -> Address { actors[i.value] }')
        t = t.replace('p.0 % 4 == p.1 % 4', 'p.0.value == p.1.value').replace('p.0 % 4 == p.2 % 4', 'p.0.value == p.2.value')
        t = t.replace('(u8, u8, u16)', '(Index<4>, Index<4>, u16)').replace('(u8, u8, u32)', '(Index<4>, Index<4>, u32)').replace('(u8, u8, u8, u32)', '(Index<4>, Index<4>, Index<4>, u32)')
    s = t.replace('@MOD@', mod).replace('@WHAT@', what)
    for pid, name, fn, ty in PROPS:
        tid = base + pid
        if idx:
            ty = ty.replace('(u8, u8, u16)', '(Index<4>, Index<4>, u16)').replace('(u8, u8, u32)', '(Index<4>, Index<4>, u32)').replace('(u8, u8, u8, u32)', '(Index<4>, Index<4>, Index<4>, u32)')
        if idx and pid in expect_fail:
            check = ('    // planted bug: must FAIL. Pre-registered minimum (original): (0, 0, 1); honest prediction (L4.1 amendment): (a, a, 1).\n'
                     '    // Asserted: a self-transfer (same actor) of amount 1. The exact indices are recorded in the event and in PROOF.md, not asserted.\n'
                     '    assert!(s.failed == 1)\n    assert!(s.shrunk[0] == s.shrunk[1])\n    assert!(s.shrunk[2] == 1)\n')
        elif pid in expect_fail:
            check = ('    // planted bug: must FAIL. Pre-registered minimum: (0, 0, 1). Found: a self-transfer (both raw indices map to the same\n'
                     '    // actor via % 4, e.g. 21 and 125 -> actor 1) of amount 1. Raw indices do not shrink to 0 because 0 would change the\n'
                     '    // actor class, so only the structure (self-transfer, amount 1) is asserted.\n'
                     '    assert!(s.failed == 1)\n    assert!(s.shrunk[0] % 4 == s.shrunk[1] % 4)\n    assert!(s.shrunk[2] == 1)\n')
        else:
            check = ('    assert!(s.failed == 0)\n    assert!(s.case == 64)\n'
                     '    assert!(gas >= 64 * 50000) // proof of work: every case deploys a token and makes several calls\n')
        s += f'''
#[test]
fn {prefix}_{name}() uses (evm: mut Evm) {{
    let actors = deploy_actors()
    let g0 = evm.gas()
    let s = summarize(check(Config::new(fixed_seed({tid * 7})).with_cases(64), |p: {ty}| {fn}(actors, p)))
    let gas = g0 - evm.gas()
    emit_pr({tid}, s, gas)
{check}}}
'''
    return s

open(os.path.join(ROOT, 'tests-erc20/src/original.fe'), 'w').write(
    gen('erc20_example', 100, 'orig', 'Properties on the UNCHANGED vendored ERC20 (examples/erc20): all expected to pass.', set()))
open(os.path.join(ROOT, 'tests-erc20/src/buggy.fe'), 'w').write(
    gen('erc20_buggy', 200, 'buggy', 'Properties on examples/erc20-buggy (PLANTED self-transfer bug): P1 and P6 must fail (self-transfer, amount 1).', {1, 6}))

open(os.path.join(ROOT, 'tests-erc20/src/original_idx.fe'), 'w').write(
    gen('erc20_example', 300, 'origidx', 'Properties on the UNCHANGED ERC20 test fixture, actors chosen with Index<4> (L4.1): all expected to pass.', set(), idx=True))
open(os.path.join(ROOT, 'tests-erc20/src/buggy_idx.fe'), 'w').write(
    gen('erc20_buggy', 400, 'buggyidx', 'Properties on examples/erc20-buggy (PLANTED self-transfer bug), actors chosen with Index<4> (L4.1): P1 and P6 must fail.', {1, 6}, idx=True))

# ---------------------------------------------------------------- stateful suites (random call sequences vs a pure reference model)
STATEFUL = '''// GENERATED by scripts/gen_erc20_tests.py -- do not edit by hand. @WHAT@
use std::evm::{Evm, Address}
use std::abi::DynArray
use sparktest::{check, Config, Seq, Index, full}
use sparktest_evm::fixed_seed
use @MOD@::CoolCoin
use ingot::actor::Actor
use ingot::client::{total_supply, balance_of, allowance, actor_transfer, actor_approve, actor_transfer_from, mint}

#[event]
struct Pw { id: u256, failed: u256, case: u256, steps: u256, original: DynArray<u256>, shrunk: DynArray<u256>, gas: u256 }

fn deploy_actors() -> [Address; 4] uses (evm: mut Evm) {
    let a0 = evm.create<Actor>(value: Wei::zero(), args: ())
    let a1 = evm.create<Actor>(value: Wei::zero(), args: ())
    let a2 = evm.create<Actor>(value: Wei::zero(), args: ())
    let a3 = evm.create<Actor>(value: Wei::zero(), args: ())
    [a0, a1, a2, a3]
}

// a fresh token per case: supply 16 to actor 0, which sends 4 to each other actor (every actor holds 4)
fn fresh_token(_ actors: [Address; 4]) -> Address uses (evm: mut Evm) {
    let token = evm.create<CoolCoin>(value: Wei::zero(), args: (16 as u256, actors[0]))
    let _ = actor_transfer(actors[0], token, actors[1], 4)
    let _ = actor_transfer(actors[0], token, actors[2], 4)
    let _ = actor_transfer(actors[0], token, actors[3], 4)
    token
}

// A command is ((kind, a, b), (c, amount)): Index<4> actors and an Index<9> amount (0..8), so the shrinker sees the real values.
//   kind 0: Transfer      from a  to b
//   kind 1: Approve       owner a spender b
//   kind 2: TransferFrom  spender a, owner b, to c
//   kind 3: Mint          to a
// Reference model: balances, allowances (owner * 4 + spender), totalSupply.
fn run_sequence(_ actors: [Address; 4], _ s: Seq<((Index<4>, Index<4>, Index<4>), (Index<4>, Index<9>)), 8>) -> bool uses (evm: mut Evm) {
    let token = fresh_token(actors)
    var bal: [u256; 4] = [4, 4, 4, 4]
    var allow: [u256; 16] = [0; 16]
    var supply: u256 = 16
    var i: usize = 0
    while i < s.len {
        let cmd = s.items[i]
        let kind = cmd.0.0.value
        let a = cmd.0.1.value
        let b = cmd.0.2.value
        let c = cmd.1.0.value
        let amount = cmd.1.1.value as u256
        var touched_o: usize = 0
        var touched_s: usize = 0
        if kind == 0 {
            let expect = bal[a] >= amount
            let got = actor_transfer(actors[a], token, actors[b], amount)
            if (got == 1) != expect { return false }
            if expect {
                bal[a] -= amount
                bal[b] += amount
            }
        } else if kind == 1 {
            if actor_approve(actors[a], token, actors[b], amount) != 1 { return false }
            allow[a * 4 + b] = amount
            touched_o = a
            touched_s = b
        } else if kind == 2 {
            let allowed = allow[b * 4 + a]
            let expect = allowed >= amount && bal[b] >= amount
            let got = actor_transfer_from(actors[a], token, actors[b], actors[c], amount)
            if (got == 1) != expect { return false }
            if expect {
                allow[b * 4 + a] -= amount
                bal[b] -= amount
                bal[c] += amount
            }
            touched_o = b
            touched_s = a
        } else {
            if !mint(token, actors[a], amount) { return false }
            supply += amount
            bal[a] += amount
        }
        // after EVERY call: the contract equals the model, and the balances add up to totalSupply
        var sum: u256 = 0
        var k: usize = 0
        while k < 4 {
            let onchain = balance_of(token, actors[k])
            if onchain != bal[k] { return false }
            sum += onchain
            k += 1
        }
        if total_supply(token) != supply { return false }
        if sum != supply { return false }
        if allowance(token, actors[touched_o], actors[touched_s]) != allow[touched_o * 4 + touched_s] { return false }
        i += 1
    }
    true
}

#[test]
fn stateful_@NAME@() uses (evm: mut Evm) {
    let actors = deploy_actors()
    let g0 = evm.gas()
    let f = full(check(Config::new(@SEED@ + zero()).with_cases(@CASES@), |s: Seq<((Index<4>, Index<4>, Index<4>), (Index<4>, Index<9>)), 8>| run_sequence(actors, s)))
    let gas = g0 - evm.gas()
    let seq_len: u256 = if f.failed == 1 { f.shrunk.get(0) } else { 0 }
    evm.emit(Pw { id: @ID@, failed: f.failed, case: f.case, steps: f.steps, original: f.original, shrunk: f.shrunk, gas })
@CHECKS@}

fn zero() -> u256 uses (evm: mut Evm) {
    if evm.chainid() == 0x1234567890abcdef { 1 } else { 0 }
}
'''
PASS_CHECKS = '''    assert!(f.failed == 0)
    assert!(f.case == 64)
    assert!(gas >= 64 * 50000)   // proof of work: every case deploys a token and replays up to 8 commands with model checks after each
'''
BUG_CHECKS = '''    // planted bug: must be found; pre-registered minimum is a sequence of 2 calls (docs/EXPECTATIONS.md, L6); the acceptance bound is 3
    assert!(f.failed == 1)
    assert!(seq_len <= 3)
'''
def gen_stateful(mod, name, what, seed, sid, checks, cases=64):
    return (STATEFUL.replace('@CASES@', str(cases)).replace('@MOD@', mod).replace('@WHAT@', what).replace('@NAME@', name)
            .replace('@SEED@', str(seed)).replace('@ID@', str(sid)).replace('@CHECKS@', checks))

open(os.path.join(ROOT, 'tests-erc20/src/stateful_orig.fe'), 'w').write(
    gen_stateful('erc20_example', 'orig', 'Stateful: the UNCHANGED ERC20 test fixture against a pure reference model (expected to pass).', 9001, 601, PASS_CHECKS))
open(os.path.join(ROOT, 'tests-erc20/src/stateful_bug.fe'), 'w').write(
    gen_stateful('erc20_stateful_bug', 'bug', 'Stateful: examples/erc20-stateful-bug (PLANTED two-call bug) against the same reference model, 64 cases.', 9002, 602, BUG_CHECKS, cases=64))
