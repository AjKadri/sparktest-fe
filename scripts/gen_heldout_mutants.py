#!/usr/bin/env python3
"""Generates examples/coolcoin-heldout/src/h01..h05.fe: five NEW single-change mutants of the Fe Guide's CoolCoin, written AFTER the ten
in gen_mutants.py and the test templates were frozen (docs/EXPECTATIONS.md, section "L9": their expected results were written before they ran).
Same construction as gen_mutants.py: the vendored listing, the contract renamed CoolCoinHNN, its #[test]s removed, exactly ONE change."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'examples/coolcoin/src/lib.fe')).read()
body = src[src.index('// ----- BEGIN UPSTREAM FILE -----\n') + len('// ----- BEGIN UPSTREAM FILE -----\n'):]
body = body[:body.index('#[test]')].rstrip() + '\n'

MUTANTS = [
 ('H01', 'spend_allowance RAISES the allowance (current + amount) instead of lowering it',
  '        self.allowances.set(key: (owner, spender), value: current - amount)\n',
  '        self.allowances.set(key: (owner, spender), value: current + amount)\n'),
 ('H02', 'transferFrom debits the spender (ctx.caller()) instead of the owner',
  '            store.spend_allowance(owner: from, spender: ctx.caller(), amount)\n            store.transfer(from, to, amount)\n',
  '            store.spend_allowance(owner: from, spender: ctx.caller(), amount)\n            store.transfer(from: ctx.caller(), to, amount)\n'),
 ('H03', 'mint credits the receiver amount + 1 (off by one)',
  '        self.total_supply += amount\n        self.balances.set(key: to, value: self.balances.get(key: to) + amount)\n',
  '        self.total_supply += amount\n        self.balances.set(key: to, value: self.balances.get(key: to) + amount + 1)\n'),
 ('H04', 'approve stores the allowance under (owner, owner) instead of (owner, spender)',
  '        self.allowances.set(key: (owner, spender), value: amount)\n\n        log.emit(event: Approval',
  '        self.allowances.set(key: (owner, owner), value: amount)\n\n        log.emit(event: Approval'),
 ('H05', 'burn no longer lowers total_supply',
  '        self.total_supply -= amount\n', ''),
]

out = os.path.join(ROOT, 'examples/coolcoin-heldout')
os.makedirs(os.path.join(out, 'src'), exist_ok=True)
open(os.path.join(out, 'fe.toml'), 'w').write('[ingot]\nname = "coolcoin_heldout"\nversion = "0.1.0"\n')
open(os.path.join(out, 'src/lib.fe'), 'w').write('// Five held-out single-change mutants of the Fe Guide CoolCoin, generated by scripts/gen_heldout_mutants.py (see README.md). Planted bugs, not real code.\n')
readme = ['# examples/coolcoin-heldout (PLANTED BUGS, generated)', '',
          'Five held-out single-change mutants of the Fe Guide\'s CoolCoin (`examples/coolcoin`), generated by `scripts/gen_heldout_mutants.py` after the test templates were frozen.',
          'Each `hNN.fe` is the vendored listing with the contract renamed `CoolCoinHNN`, the listing\'s own tests removed, and exactly one change:', '', '| mutant | single change |', '|---|---|']
for mid, desc, old, new in MUTANTS:
    assert body.count(old) == 1, f'{mid}: the text to mutate must occur exactly once, found {body.count(old)}'
    mutated = body.replace(old, new)
    assert mutated != body
    text = (f'// GENERATED by scripts/gen_heldout_mutants.py. PLANTED BUG {mid}: {desc}.\n'
            f'// The Fe Guide CoolCoin (examples/coolcoin) with the contract renamed CoolCoin{mid}, its #[test]s removed and this one change. Not real code.\n'
            + mutated.replace('pub contract CoolCoin ', f'pub contract CoolCoin{mid} '))
    assert f'pub contract CoolCoin{mid} ' in text
    open(os.path.join(out, 'src', mid.lower() + '.fe'), 'w').write(text)
    readme.append(f'| {mid} | {desc} |')
open(os.path.join(out, 'README.md'), 'w').write('\n'.join(readme) + '\n')
print('generated 5 held-out mutants')
