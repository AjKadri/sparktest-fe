#!/usr/bin/env python3
"""Generates examples/coolcoin-mutants/src/m01..m10.fe: ten single-change mutants of the Fe Guide's CoolCoin (examples/coolcoin).
Each file is the vendored listing with (1) the contract renamed CoolCoinMNN, (2) the listing's own #[test] functions removed, and (3) exactly ONE mutation."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'examples/coolcoin/src/lib.fe')).read()
body = src[src.index('// ----- BEGIN UPSTREAM FILE -----\n') + len('// ----- BEGIN UPSTREAM FILE -----\n'):]
body = body[:body.index('#[test]')].rstrip() + '\n'   # the listing's tests are not part of a mutant

MUTANTS = [
 ('M01', 'transfer credits the receiver amount + 1',
  '        self.balances.set(key: from, value: from_balance - amount)\n        self.balances.set(key: to, value: self.balances.get(key: to) + amount)\n',
  '        self.balances.set(key: from, value: from_balance - amount)\n        self.balances.set(key: to, value: self.balances.get(key: to) + amount + 1)\n'),
 ('M02', 'the balance assert in transfer is removed',
  '        assert!(from_balance >= amount, "transfer amount exceeds balance")\n', ''),
 ('M03', 'transferFrom swaps from and to in the inner transfer',
  '            store.spend_allowance(owner: from, spender: ctx.caller(), amount)\n            store.transfer(from, to, amount)\n',
  '            store.spend_allowance(owner: from, spender: ctx.caller(), amount)\n            store.transfer(from: to, to: from, amount)\n'),
 ('M04', 'spend_allowance no longer lowers the allowance',
  '        self.allowances.set(key: (owner, spender), value: current - amount)\n', ''),
 ('M05', 'transfer credits the receiver first, then debits from the stale sender balance',
  '        self.balances.set(key: from, value: from_balance - amount)\n        self.balances.set(key: to, value: self.balances.get(key: to) + amount)\n',
  '        self.balances.set(key: to, value: self.balances.get(key: to) + amount)\n        self.balances.set(key: from, value: from_balance - amount)\n'),
 ('M06', 'transfer balance check >= becomes >',
  'assert!(from_balance >= amount, "transfer amount exceeds balance")', 'assert!(from_balance > amount, "transfer amount exceeds balance")'),
 ('M07', 'spend_allowance check >= becomes >',
  'assert!(current >= amount, "insufficient allowance")', 'assert!(current > amount, "insufficient allowance")'),
 ('M08', 'transfer no longer emits the Transfer event',
  '\n        log.emit(event: Transfer { from, to, value: amount })\n', '\n'),
 ('M09', 'mint no longer increases total_supply',
  '        self.total_supply += amount\n', ''),
 ('M10', 'mint no longer requires the MINTER role',
  '            auth.require(role: MINTER)\n', ''),
]

out = os.path.join(ROOT, 'examples/coolcoin-mutants')
os.makedirs(os.path.join(out, 'src'), exist_ok=True)
open(os.path.join(out, 'fe.toml'), 'w').write('[ingot]\nname = "coolcoin_mutants"\nversion = "0.1.0"\n')
open(os.path.join(out, 'src/lib.fe'), 'w').write('// Ten single-change mutants of the Fe Guide CoolCoin, generated by scripts/gen_mutants.py (see README.md). Planted bugs, not real code.\n')
readme = ['# examples/coolcoin-mutants (PLANTED BUGS, generated)', '',
          'Ten single-change mutants of the Fe Guide\'s CoolCoin (`examples/coolcoin`), generated by `scripts/gen_mutants.py`. Each `mNN.fe` is the vendored listing with the contract renamed',
          '`CoolCoinMNN`, the listing\'s own tests removed, and exactly one change:', '', '| mutant | single change |', '|---|---|']
for mid, desc, old, new in MUTANTS:
    assert body.count(old) == 1, f'{mid}: the text to mutate must occur exactly once, found {body.count(old)}'
    mutated = body.replace(old, new)
    assert mutated != body
    text = (f'// GENERATED by scripts/gen_mutants.py. PLANTED BUG {mid}: {desc}.\n'
            f'// The Fe Guide CoolCoin (examples/coolcoin) with the contract renamed CoolCoin{mid}, its #[test]s removed and this one change. Not real code.\n'
            + mutated.replace('pub contract CoolCoin ', f'pub contract CoolCoin{mid} '))
    assert f'pub contract CoolCoin{mid} ' in text
    open(os.path.join(out, 'src', mid.lower() + '.fe'), 'w').write(text)
    readme.append(f'| {mid} | {desc} |')
open(os.path.join(out, 'README.md'), 'w').write('\n'.join(readme) + '\n')
print('generated 10 mutants')
