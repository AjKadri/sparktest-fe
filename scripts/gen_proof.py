#!/usr/bin/env python3
"""Generates the proof-scenario code from proof/registry.json:
   props/src/proof_scenarios.fe, tests-evm/src/proof.fe, proof-native/src/lib.fe."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
reg = json.load(open(os.path.join(ROOT, 'proof/registry.json')))
sreg = json.load(open(os.path.join(ROOT, 'proof/stateful.json')))
HDR = '// GENERATED by scripts/gen_proof.py from proof/registry.json -- do not edit by hand.\n'

# 1. scenarios in props
o = [HDR + 'use sparktest::{Config, check, Summary, summarize}\n']
for r in reg:
    o.append(f"pub fn sc_{r['name']}(_ seed: u256) -> Summary {{ summarize(check(Config::new(seed).with_cases({r['cases']}), {r['prop'].replace('props::', 'ingot::')})) }}")
o[0] = o[0].replace('use sparktest::{Config, check, Summary, summarize}', 'use sparktest::{Config, check, Summary, summarize, Full, full}')
for r in sreg:
    o.append(f"pub fn sw_{r['name']}(_ seed: u256) -> Full {{ full(check(Config::new(seed).with_cases({r['cases']}), {r['prop'].replace('props::', 'ingot::')})) }}")
open(os.path.join(ROOT, 'props/src/proof_scenarios.fe'), 'w').write('\n'.join(o) + '\n')

# 2. sonatina test: emits one event per scenario (13 words: id, failed, case, steps, original[4], shrunk[4], gas)
e = [HDR + '''use std::evm::Evm
use sparktest::Summary

#[event]
struct Pr { id: u256, failed: u256, case: u256, steps: u256, o0: u256, o1: u256, o2: u256, o3: u256, s0: u256, s1: u256, s2: u256, s3: u256, gas: u256 }

fn zero() -> u256 uses (evm: mut Evm) {
    if evm.chainid() == 0x1234567890abcdef { 1 } else { 0 }
}

fn emit_pr(_ id: u256, _ s: Summary, _ gas: u256) uses (evm: mut Evm) {
    evm.emit(Pr { id, failed: s.failed, case: s.case, steps: s.steps,
        o0: s.original[0], o1: s.original[1], o2: s.original[2], o3: s.original[3],
        s0: s.shrunk[0], s1: s.shrunk[1], s2: s.shrunk[2], s3: s.shrunk[3], gas })
}
''']
for r in reg:
    e.append(f'''#[test]
fn proof_{r['name']}() uses (evm: mut Evm) {{
    let z = zero()
    let g0 = evm.gas()
    let s = props::proof_scenarios::sc_{r['name']}({r['seed']} + z)
    emit_pr({r['id']}, s, g0 - evm.gas())
}}
''')
e.append('''
#[event]
struct Pw { id: u256, failed: u256, case: u256, steps: u256, original: DynArray<u256>, shrunk: DynArray<u256>, gas: u256 }
''')
for r in sreg:
    e.append(f'''#[test]
fn stateful_{r['name']}() uses (evm: mut Evm) {{
    let z = zero()
    let g0 = evm.gas()
    let f = props::proof_scenarios::sw_{r['name']}({r['seed']} + z)
    evm.emit(Pw {{ id: {r['id']}, failed: f.failed, case: f.case, steps: f.steps, original: f.original, shrunk: f.shrunk, gas: g0 - evm.gas() }})
}}
''')
e[0] = e[0].replace('use std::evm::Evm\n', 'use std::evm::Evm\nuse std::abi::DynArray\n')
open(os.path.join(ROOT, 'tests-evm/src/proof.fe'), 'w').write('\n'.join(e))

# 3. native executable
n = [HDR + '''use std::io::Stdout
use sparktest::Full
use sparktest_native::{opaque_zero, print_summary, print_full}
''']
n.append('pub fn main() -> i32 uses (out: mut Stdout) {\n    let z = opaque_zero()')
for r in reg:
    n.append(f"    print_summary(\"{r['name']}\", props::proof_scenarios::sc_{r['name']}({r['seed']} + z))")
for r in sreg:
    n.append(f"    print_full(\"{r['name']}\", props::proof_scenarios::sw_{r['name']}({r['seed']} + z))")
n.append('    0\n}\n')
open(os.path.join(ROOT, 'proof-native/src/lib.fe'), 'w').write('\n'.join(n))
