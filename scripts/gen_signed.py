#!/usr/bin/env python3
"""Generates sparktest/src/signed.fe: Arbitrary + Shrink + Encode + Decode for i8, i16, i32, i64, i128, i256 (L10).
Values are handled as N-bit two's-complement patterns in a u256. Encode is the sign-extended 256-bit word (`to_word`), so -1 is 2^256 - 1 in every width."""
HEAD = '''// GENERATED by scripts/gen_signed.py -- do not edit by hand. Signed integers (L10): generated like the unsigned widths, shrunk toward 0.
use std::abi::DynArray
use ingot::{Rng, Arbitrary, Shrink, Encode, Decode, one_word, MAX}
use core::num::IntWord

fn width_mask(_ bits: u256) -> u256 {
    if bits == 256 { MAX } else { (1 << bits) - 1 }
}

// an N-bit two's-complement pattern: about 1 draw in 4 is an edge value (min, -1, 0, 1, 2, -2, max, +-2^k), the rest are uniform over all patterns
pub fn signed_bits<R: Rng>(_ rng: mut R, _ bits: u256) -> u256 {
    let mask = width_mask(bits)
    let sign: u256 = 1 << (bits - 1)
    if rng.next() % 4 == 0 {
        let pick = rng.next() % 9
        let k = rng.next() % (bits - 1)
        if pick == 0 { return 0 }
        if pick == 1 { return 1 }
        if pick == 2 { return 2 }
        if pick == 3 { return sign - 1 }                      // max
        if pick == 4 { return sign }                          // min
        if pick == 5 { return mask }                          // -1
        if pick == 6 { return mask - 1 }                      // -2
        if pick == 7 { return 1 << k }                        // +2^k
        return (0 as u256).wrapping_sub(1 << k) & mask       // -2^k
    }
    var v = rng.next()
    if bits > 64 { v = v | (rng.next() << 64) }
    if bits > 128 { v = v | (rng.next() << 128) }
    if bits > 192 { v = v | (rng.next() << 192) }
    v & mask
}

// Shrink toward 0. Candidates: 0; for a negative x whose absolute value fits, +|x|; then the magnitude's u256 candidates (halving toward 0, then
// minus one) with the original sign. Returns an N-bit pattern.
pub fn signed_shrink(_ word: u256, _ bits: u256, _ i: u256) -> Option<u256> {
    let mask = width_mask(bits)
    let sign: u256 = 1 << (bits - 1)
    let b = word & mask
    if b == 0 {
        return Option::None
    }
    let neg = b & sign != 0
    let m = if neg { (0 as u256).wrapping_sub(b) & mask } else { b }
    if i == 0 {
        return Option::Some(0)
    }
    let offset: u256 = if neg && m < sign { 1 } else { 0 }
    if offset == 1 && i == 1 {
        return Option::Some(m)
    }
    match m.shrink_step(i - offset) {
        Option::Some(m2) => Option::Some(if neg { (0 as u256).wrapping_sub(m2) & mask } else { m2 })
        Option::None => Option::None
    }
}

// is `word` a valid sign-extended encoding of an N-bit value (every bit above bit N-1 equals bit N-1)
pub fn signed_fits(_ word: u256, _ bits: u256) -> bool {
    if bits == 256 {
        return true
    }
    let hi = word >> (bits - 1)
    hi == 0 || hi == (MAX >> (bits - 1))
}
'''
out = [HEAD]
for w in (8, 16, 32, 64, 128, 256):
    t = f'i{w}'
    out.append(f'''
impl Arbitrary for {t} {{
    fn arbitrary<R: Rng>(_ rng: mut R) -> Self {{
        {t}::from_word(signed_bits(mut rng, {w}))
    }}
}}

impl Shrink for {t} {{
    fn shrink_step(self, _ i: u256) -> Option<Self> {{
        match signed_shrink(self.to_word(), {w}, i) {{
            Option::Some(b) => Option::Some({t}::from_word(b))
            Option::None => Option::None
        }}
    }}
}}

impl Decode for {t} {{
    fn decode(_ w: DynArray<u256>, _ pos: usize) -> (Self, usize) {{
        ({t}::from_word(w.get(pos)), pos + 1)
    }}
    fn fits(_ w: [u256; 64], _ pos: usize) -> usize {{
        if pos < 64 && signed_fits(w[pos], {w}) {{ pos + 1 }} else {{ 0 }}
    }}
    fn mark_signed(_ m: mut [bool; 64], _ pos: usize) -> usize {{
        if pos < 64 {{
            m[pos] = true
        }}
        pos + 1
    }}
}}

impl Encode for {t} {{
    fn words(self) -> DynArray<u256> {{ one_word(self.to_word()) }}
}}
''')
import os
open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'sparktest/src/signed.fe'), 'w').write(''.join(out))
