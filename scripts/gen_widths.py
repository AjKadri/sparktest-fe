#!/usr/bin/env python3
"""Generates sparktest/src/widths.fe: Arbitrary + Shrink + Encode for u8, u16, u32, u64, u128."""
out = ['// GENERATED by scripts/gen_widths.py -- do not edit by hand.',
       'use std::abi::DynArray', 'use ingot::{Rng, Arbitrary, Shrink, Encode, one_word}', '',
       '// A value in [0, 2^bits) as a u256: about 1 in 4 draws is an edge value',
       '// (0, 1, 2, max, max-1, 2^k, 2^k-1, 2^k+1 for a random k < bits), the rest are uniform.',
       'pub fn bits_value<R: Rng>(_ rng: mut R, _ bits: u256) -> u256 {',
       '    let top: u256 = (1 << bits) - 1',
       '    if rng.next() % 4 == 0 {',
       '        let pick = rng.next() % 8',
       '        let k = rng.next() % bits',
       '        if pick == 0 { return 0 }',
       '        if pick == 1 { return 1 }',
       '        if pick == 2 { return 2 }',
       '        if pick == 3 { return top }',
       '        if pick == 4 { return top - 1 }',
       '        let p = 1 << k',
       '        if pick == 5 { return p }',
       '        if pick == 6 { return p - 1 }',
       '        return p + 1',
       '    }',
       '    var v = rng.next()',
       '    if bits > 64 { v = v | (rng.next() << 64) }',
       '    if bits > 128 { v = v | (rng.next() << 128) }',
       '    if bits > 192 { v = v | (rng.next() << 192) }',
       '    v & top',
       '}', '',
       '// the u256 shrink candidates, reused for every width (candidates are < self, so they fit)',
       'fn shrink_bits(_ x: u256, _ i: u256) -> Option<u256> {',
       '    x.shrink_step(i)',
       '}', '']
for w in (8, 16, 32, 64, 128):
    t = f'u{w}'
    out += [f'impl Arbitrary for {t} {{',
            f'    fn arbitrary<R: Rng>(_ rng: mut R) -> Self {{',
            f'        let v = bits_value(mut rng, {w})',
            f'        v.downcast_truncate()',
            f'    }}', '}', '',
            f'impl Shrink for {t} {{',
            f'    fn shrink_step(self, _ i: u256) -> Option<Self> {{',
            f'        match shrink_bits(self as u256, i) {{',
            f'            Option::Some(c) => Option::Some(c.downcast_truncate())',
            f'            Option::None => Option::None',
            f'        }}',
            f'    }}', '}', '',
            f'impl Encode for {t} {{',
            f'    fn words(self) -> DynArray<u256> {{ one_word(self as u256) }}', '}', '']
open('sparktest/src/widths.fe', 'w').write('\n'.join(out))
