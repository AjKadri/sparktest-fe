"""L10 section of docs/PROOF.md: custom generators, assume with discard counting, regression seeds, signed integers. Imported by proof.py."""
import re

GROUPS = [
    ('generators', 'Custom generators (`Gen`, `between`, `one_of`, `pair`, `dependent`, `mapped`, `check_gen`)',
     ['between_', 'one_of_', 'mapped_', 'pair_', 'dependent_', 'check_gen_is_deterministic']),
    ('assume', 'assume with discard counting (`Judged`, `check_assume`, `assume_guard`)',
     ['a_weak_premise_reports_its_discard_rate', 'a_property_that_discards_everything', 'discarding_more_than_the_threshold', 'a_mild_premise_is_held',
      'a_failing_property_with_a_premise', 'assume_works_with_a_generator', 'judged_maps_booleans']),
    ('regression', 'Regression seeds (`Config::with_regressions`)',
     ['a_listed_seed_fails', 'the_same_seed_passes_after_the_fix', 'the_reported_seed_replays', 'no_regressions_means', 'a_regression_that_passes', 'regressions_also_apply', 'more_than_eight']),
    ('signed', 'Signed integers (`i8` to `i256`)',
     ['i8_draws_reach', 'a_negative_bound', 'a_positive_bound', 'an_always_false_property_shrinks_to_zero', 'the_most_negative_value', 'a_negative_value_tries', 'encode_and_decode_round_trip_signed', 'signed_values_work_inside_tuples']),
]

def _results(run, cwd):
    out = run(['fe', 'test'], cwd=cwd).stdout
    return {m.group(2): m.group(1) for m in (re.match(r'(PASS|FAIL)\s+\[[^\]]*\]\s+(\S+)', l) for l in out.splitlines()) if m}

def _events(run):
    out = run(['fe', 'test', '--filter', 'a_', '--show-logs'], cwd='tests-erc20').stdout
    ev = {'vt': {}, 'ad': {}}
    for line in out.splitlines():
        m = re.search(r'data: (0x[0-9a-f]*) \}', line)
        if m:
            h = m.group(1)[2:]
            w = [int(h[i:i + 64], 16) for i in range(0, len(h), 64)]
            if len(w) == 10 and w[0] in (1, 2) and w[7] <= 64:
                ev['vt'][w[0]] = w
            elif len(w) == 5 and w[0] in (1, 2) and w[1] == 64:
                ev['ad'][w[0]] = w
    return ev

def section(run, problems):
    evm = _results(run, 'tests-evm')
    nat = _results(run, 'tests-native')
    s = ['## L10: generators, assume, regression seeds, signed integers', '',
         'Expected results were written before the runs (docs/EXPECTATIONS.md, section "L10"). Sources: `sparktest/src/gens.fe`, `assume.fe`, `signed.fe` (generated by `scripts/gen_signed.py`); tests: `tests-evm/src/{gens,assume,regression,signed}.fe` and the same files in `tests-native/src`; ERC20 examples: `tests-erc20/src/{valid_transfer,assume_demo}.fe`.', '',
         '| area | test | sonatina | native |', '|---|---|---|---|']
    for key, title, prefixes in GROUPS:
        for name in sorted(n for n in evm if any(n.startswith(p) for p in prefixes)):
            e = evm[name]
            n = nat.get(name, 'MISSING')
            if e != 'PASS' or n != 'PASS':
                problems.append(f'L10 {name}: sonatina {e}, native {n}')
            s.append(f"| {title} | {name.replace('_', ' ')} | {e} | {n} |")
    ev = _events(run)
    vt, ad = ev['vt'], ev['ad']
    s += ['', '### The `check_gen` ERC20 example (sonatina): a valid transfer from a dependent generator', '',
          'Balances at the start: 700, 100, 200, 0. The generator picks a sender and a receiver, then an amount from `0..=balance(sender)`: `dependent(pair(between(0, 3), between(0, 3)), |ft| between(0, balance(ft.0)))`. No modulo or `Index` trick; the older properties (P1 to P6) are unchanged.', '',
          '| run | result | case | shrink steps | shrunk (sender, receiver, amount) | calls accepted / attempted | vacuous? |', '|---|---|---|---|---|---|---|']
    for i, label in ((1, 'unchanged fixture (expected: passes, every call succeeds)'), (2, 'planted self-transfer bug (expected: fails, sender == receiver, amount 1)')):
        w = vt.get(i)
        if w is None:
            problems.append(f'L10 valid-transfer example {i}: no result'); continue
        s.append(f"| {label} | {'FAILED' if w[1] else 'passed 64 cases'} | {w[2] + 1 if w[1] else '-'} | {w[3] if w[1] else '-'} | {'(%d, %d, %d)' % (w[4], w[5], w[6]) if w[1] else '-'} | {w[8]} / {w[7]} | {'no' if w[9] == 0 else 'reason %d' % w[9]} |")
    if vt.get(1) and not (vt[1][1] == 0 and vt[1][7] == 64 and vt[1][8] == 64): problems.append(f'valid transfer on the unchanged fixture: {vt[1]}')
    if vt.get(2) and not (vt[2][1] == 1 and vt[2][4] == vt[2][5] and vt[2][6] == 1): problems.append(f'valid transfer on the planted bug: {vt[2]}')
    s += ['', '### Discard rates on the ERC20 fixture (sonatina)', '',
          'A P3-style property over a raw `u32` amount with the premise "the amount is within the balance" (1000), 64 cases. Verdict codes: 0 held, 1 failed, 2 nothing accepted, 100 too many discarded (more than 90%).', '',
          '| run | cases | discarded | discard percent | verdict |', '|---|---|---|---|---|']
    for i, label in ((1, 'weak premise: amount <= 1000'), (2, 'premise that never holds: amount == 123456789')):
        w = ad.get(i)
        if w is None:
            problems.append(f'L10 discard demo {i}: no result'); continue
        s.append(f"| {label} | {w[1]} | {w[2]} | {w[3]}% | {w[4]}{' (vacuous: too many discards)' if w[4] == 100 else ' (vacuous: nothing accepted)' if w[4] == 2 else ''} |")
    s += ['', 'Rerun: `cd tests-evm && fe test`, `cd tests-native && fe test`, `cd tests-erc20 && fe test --filter a_ --show-logs`.', '']
    return s
